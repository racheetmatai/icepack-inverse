def figure3() -> list[Path]:
    r, v = region_context(), aggregate_velocity_grid()
    coords = np.load(GATE1 / "state_coordinates.npy") / 1000
    cfield = np.load(GATE1 / "state_C.npy")
    x, y = r["x_grid"] / 1000, r["y_grid"] / 1000
