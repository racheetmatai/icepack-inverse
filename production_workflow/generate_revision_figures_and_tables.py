def generate_tables() -> list[Path]:
    outputs = []
    predictor_rows = []
    for feature, (name, unit, source) in FEATURES.items():
        predictor_rows.append({"predictor": feature, "description": name, "unit": unit, "source_or_derivation": source,
                               **{cfg: "yes" if feature in CONFIG_FEATURES[cfg] else "" for cfg in CONFIGS}})
    t1 = pd.DataFrame(predictor_rows)
    p = OUT / "table1_predictors_and_configurations.csv"; t1.to_csv(p, index=False); outputs.append(p)

    summary = pd.read_csv(REPORTING / "square_equal_weight_summary.csv").drop(columns=["P_exp_median_percent"])
    perf = pd.read_csv(FORWARD / "control_population_metrics.csv")
    perf = perf.loc[(perf["control_kind"] == "median") & perf["experiment"].str.fullmatch(r"SQ\d{2}")
                    & (perf["population"] == "central_50km") & (perf["support_stratum"] == "all")].copy()
    perf["relative_rmse_uniform"] = perf["vector_rmse_m_per_a"] / perf["uniform_vector_rmse_m_per_a"]
    ratio_summary = perf.groupby("configuration")["relative_rmse_uniform"].agg(
        median_relative_RMSE_to_uniform="median",
        q25_relative_RMSE_to_uniform=lambda x: x.quantile(.25),
        q75_relative_RMSE_to_uniform=lambda x: x.quantile(.75),
    ).reset_index()
    summary = summary.merge(ratio_summary, on="configuration", validate="one_to_one")
    summary.insert(1, "configuration_label", summary["configuration"].map(CONFIG_LABELS))
    summary = summary.rename(columns={
        "vector_RMSE_median_m_per_a": "median_vector_RMSE_m_per_a",
        "vector_RMSE_q25_m_per_a": "q25_vector_RMSE_m_per_a",
        "vector_RMSE_q75_m_per_a": "q75_vector_RMSE_m_per_a",
    })
    p = OUT / "table2_primary_performance.csv"; summary.to_csv(p, index=False); outputs.append(p)

    support = support_rows()
    merged = support.merge(perf[["experiment", "configuration", "vector_rmse_m_per_a", "uniform_vector_rmse_m_per_a",
                                 "relative_rmse_uniform"]],
                           on=["experiment", "configuration"], validate="one_to_one")
    failures = merged.loc[(merged["both_fraction"] >= .95) & (merged["relative_rmse_uniform"] >= 1)].copy()
    failures = failures.sort_values(["experiment", "relative_rmse_uniform"], ascending=[True, False]).groupby("experiment", as_index=False).head(1)
    failures = failures[["experiment", "configuration", "minimum_marginal_coverage", "joint_coverage", "both_fraction",
                         "vector_rmse_m_per_a", "uniform_vector_rmse_m_per_a", "relative_rmse_uniform"]]
    failures.insert(2, "configuration_label", failures["configuration"].map(CONFIG_LABELS))
    p = OUT / "table3_high_support_low_skill_examples.csv"; failures.to_csv(p, index=False); outputs.append(p)
    full = merged.loc[(merged["both_fraction"] >= .95) & (merged["relative_rmse_uniform"] >= 1)].copy()
    p = OUT / "appendix_table_high_support_low_skill_all_cases.csv"; full.to_csv(p, index=False); outputs.append(p)

    # Compact LaTeX snippets; captions remain in the manuscript source.
    for frame, name in [(t1, "table1_predictors_and_configurations.tex"),
                        (summary, "table2_primary_performance.tex"),
                        (failures, "table3_high_support_low_skill_examples.tex")]:
        p = OUT / name
        def tex(value: object) -> str:
            if isinstance(value, (float, np.floating)):
                value = f"{value:.3f}"
            return str(value).replace("_", r"\_").replace("%", r"\%")
        lines = [r"\begin{tabular}{" + "l" * len(frame.columns) + "}",
                 " & ".join(tex(c) for c in frame.columns) + r" \\", r"\hline"]
        lines.extend(" & ".join(tex(v) for v in row) + r" \\" for row in frame.itertuples(index=False, name=None))
        lines.append(r"\end{tabular}")
        p.write_text("\n".join(lines) + "\n", encoding="utf-8")
        outputs.append(p)
    return outputs


def load_c_fields(config: str) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, pd.DataFrame]:
    squares = square_table()
    coords = reference = eligible = None
    predicted = np.full(1, np.nan)
    pieces = []
    for row in squares.itertuples():
        with np.load(PREDICTIONS / f"{row.square_id}_{config}.npz", allow_pickle=False) as z:
            c = z["coordinates"].astype(float); e = z["eligible_mask"].astype(bool)
            ref = z["reference_log_C"].astype(float); pred = z["median_log_C"].astype(float)
        if coords is None:
            coords, eligible, reference = c, e, ref
            predicted = np.full_like(ref, np.nan)
        elif not (np.array_equal(coords, c) and np.array_equal(eligible, e) and np.array_equal(reference, ref)):
            raise RuntimeError("Full-mesh prediction identity mismatch")
        mask = e & (c[:, 0] >= row.test_xmin_m) & (c[:, 0] <= row.test_xmax_m) \
                 & (c[:, 1] >= row.test_ymin_m) & (c[:, 1] <= row.test_ymax_m)
        predicted[mask] = pred[mask]
        pieces.append(pd.DataFrame({"square": row.square_id, "mask_index": np.flatnonzero(mask)}))
    mask = np.isfinite(predicted) & eligible
    return coords[mask] / 1000, reference[mask], predicted[mask], predicted[mask] - reference[mask], squares


def load_normalized_velocity_error(config: str) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    metrics = pd.read_csv(FORWARD / "control_population_metrics.csv")
    metrics = metrics.loc[(metrics["control_kind"] == "median") & metrics["experiment"].str.fullmatch(r"SQ\d{2}")
                          & (metrics["population"] == "central_50km") & (metrics["support_stratum"] == "all")
                          & (metrics["configuration"] == config)].set_index("experiment")
    with np.load(FOOTPRINT_ERRORS / f"{config}_ten_square_footprint_errors.npz", allow_pickle=False) as z:
        chunks = []
        for number in range(1, 11):
            mask = (z["square_number"] == number) & z["central"].astype(bool)
            population_rms = float(metrics.loc[f"SQ{number:02d}", "observed_vector_rms_m_per_a"])
            chunks.append(np.column_stack([z["x"][mask] / 1000.0, z["y"][mask] / 1000.0,
                                           100.0 * z["error_magnitude"][mask] / population_rms]))
    values = np.concatenate(chunks)
    return values[:, 0], values[:, 1], values[:, 2]


