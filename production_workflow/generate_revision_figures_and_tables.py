def aggregate_velocity_grid() -> dict[str, np.ndarray]:
    cache = OUT / "revision_velocity_grid_5km.npz"
    if cache.exists():
        with np.load(cache, allow_pickle=False) as z:
            return {k: z[k] for k in z.files}
    g = grid_context()
    xg, yg = g["x_grid"], g["y_grid"]
    sums = {k: np.zeros((len(yg), len(xg)), dtype=float) for k in ("speed", "error")}
    count = np.zeros((len(yg), len(xg)), dtype=np.int64)
    columns = ["x", "y", "observed_speed", "observed_vx", "observed_vy", "inversion_vx", "inversion_vy"]
    source = DATASET / "canonical_master_dataset.csv.gz"
    for chunk in pd.read_csv(source, usecols=columns, chunksize=200_000):
        ix = np.rint((chunk["x"].to_numpy() - xg[0]) / 5000).astype(int)
        iy = np.rint((chunk["y"].to_numpy() - yg[0]) / 5000).astype(int)
        valid = (ix >= 0) & (ix < len(xg)) & (iy >= 0) & (iy < len(yg))
        speed = chunk["observed_speed"].to_numpy()
        err = np.hypot(chunk["inversion_vx"] - chunk["observed_vx"],
                       chunk["inversion_vy"] - chunk["observed_vy"]).to_numpy()
        valid &= np.isfinite(speed) & np.isfinite(err)
        np.add.at(sums["speed"], (iy[valid], ix[valid]), speed[valid])
        np.add.at(sums["error"], (iy[valid], ix[valid]), err[valid])
        np.add.at(count, (iy[valid], ix[valid]), 1)
    result = {"x_grid": xg, "y_grid": yg, "count": count}
    for key, values in sums.items():
        result[key] = np.divide(values, count, out=np.full_like(values, np.nan), where=count > 0)
    np.savez_compressed(cache, **result)
    return result


def domain_outline() -> dict:
    return json.loads(DOMAIN_OUTLINE.read_text(encoding="utf-8"))


def map_axes(ax: plt.Axes, outline: np.ndarray) -> None:
    # Use the complete model-domain linework, including the open-ocean ice-front
    # (terminus) segments.  The legacy flattened outline omitted those segments.
    for feature in domain_outline()["features"]:
        geometry = feature["geometry"]
        lines = geometry["coordinates"] if geometry["type"] == "MultiLineString" else [geometry["coordinates"]]
        for line in lines:
            points = np.asarray(line, dtype=float) / 1000.0
            ax.plot(points[:, 0], points[:, 1], color="0.08", lw=0.85, zorder=8)
    ax.set_aspect("equal")
    ax.set_xlabel("Polar stereographic x (km)")
    ax.set_ylabel("Polar stereographic y (km)")
    ax.tick_params(direction="out", length=2.5)


def antarctica_rings() -> list[np.ndarray]:
    payload = json.loads(ANTARCTICA_LAND.read_text(encoding="utf-8"))
    transformer = Transformer.from_crs("EPSG:4326", "EPSG:3031", always_xy=True)
    rings: list[np.ndarray] = []
    for feature in payload["features"]:
        geometry = feature["geometry"]
        polygons = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
        for polygon in polygons:
            if not polygon:
                continue
            ring = np.asarray(polygon[0], dtype=float)
            if ring.ndim != 2 or ring.shape[1] != 2 or np.nanmin(ring[:, 1]) > -60:
                continue
            xx, yy = transformer.transform(ring[:, 0], ring[:, 1])
            rings.append(np.column_stack([xx, yy]) / 1000.0)
    if not rings:
        raise RuntimeError("Natural Earth input contains no Antarctic land rings")
    return rings


def add_antarctica_locator(ax: plt.Axes, outline: np.ndarray) -> None:
    inset = ax.inset_axes([0.765, 0.755, 0.21, 0.21])
    for ring in antarctica_rings():
        inset.add_patch(Polygon(ring, closed=True, facecolor="0.78", edgecolor="0.25", lw=0.35))
    xmin, ymin = np.min(outline, axis=0) / 1000.0
    xmax, ymax = np.max(outline, axis=0) / 1000.0
    inset.add_patch(Rectangle((xmin, ymin), xmax-xmin, ymax-ymin, fill=False, edgecolor="#8B0015", lw=1.1))
    inset.set_xlim(-2900, 2900); inset.set_ylim(-2600, 2600)
    inset.set_aspect("equal"); inset.set_xticks([]); inset.set_yticks([])
    inset.set_facecolor("#DDEEF4")
    for spine in inset.spines.values():
        spine.set_linewidth(.45); spine.set_color("0.35")


def draw_speed_basemap(ax: plt.Axes, r: dict[str, np.ndarray], v: dict[str, np.ndarray], alpha: float = .24) -> None:
    x, y = r["x_grid"] / 1000.0, r["y_grid"] / 1000.0
    extent = [x[0] - 2.5, x[-1] + 2.5, y[0] - 2.5, y[-1] + 2.5]
    speed = np.ma.masked_where(~r["eligible"] | ~np.isfinite(v["speed"]), v["speed"])
    ax.imshow(speed, origin="lower", extent=extent, cmap="Greys",
              norm=LogNorm(vmin=max(1, np.nanpercentile(speed.compressed(), 1)),
                           vmax=np.nanpercentile(speed.compressed(), 99.5)),
              alpha=alpha, zorder=0)


